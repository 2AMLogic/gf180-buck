"""Unit tests for layout/: the committed GDS is what the generator produces, and
the power path measured out of it meets the 500 mA EM row.

Drift guard, not a redraw: CI re-hashes layout/buck.gds against the manifest,
which catches an edited GDS but not a gen_layout.py that has drifted from the
GDS it is cited as producing (manifests/item2-attestation.json names
`python3 layout/gen_layout.py` as the generator).

Needs the klayout Python module (both scripts import klayout.db); no PDK, no
ngspice, no klt. The first test regenerates the whole layout, so it takes tens
of seconds.

Run: python3 -m unittest discover -s layout -p 'test_*.py'
(not `-I`: it drops the user site-packages directory, which is where a
no-host-install klayout usually lives)
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import unittest

import klayout.db as db

HERE = os.path.dirname(os.path.abspath(__file__))
GDS = os.path.join(HERE, "buck.gds")


_GEN = {}   # filled by setUpModule: "gds", "info" (parsed JSON), "run" (CompletedProcess)
_TMP = None


def setUpModule():
    """One shared generator run into a temp dir, so selecting any single test works.

    layout/buck.info.json is an untracked, locally generated by-product (#159);
    the tests read the fault coordinates from this run, never from a checkout copy.
    """
    global _TMP
    _TMP = tempfile.TemporaryDirectory()
    out = os.path.join(_TMP.name, "buck.gds")
    info = os.path.join(_TMP.name, "buck.info.json")
    r = run("gen_layout.py", "--out", out, "--info", info)
    _GEN["run"] = r
    if r.returncode == 0:
        _GEN["gds"] = out
        with open(info) as fh:
            _GEN["info"] = json.load(fh)


def tearDownModule():
    _TMP.cleanup()


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def run(script, *args):
    """Run one of the layout scripts under this interpreter (see above re `-I`)."""
    return subprocess.run([sys.executable, os.path.join(HERE, script), *args],
                          capture_output=True, text=True)


class GeneratorTests(unittest.TestCase):
    def test_generator_output_matches_committed_gds(self):
        """gen_layout.py still reproduces buck.gds byte for byte."""
        r = _GEN["run"]
        self.assertEqual(r.returncode, 0,
                         "gen_layout.py failed (%d):\n%s%s" % (r.returncode, r.stdout, r.stderr))
        out = _GEN["gds"]
        self.assertEqual(
            sha256(out), sha256(GDS),
            "gen_layout.py no longer reproduces layout/buck.gds. If the generator "
            "change is intended, regenerate the GDS and re-attest T1 item 2 "
            "(layout/README.md), otherwise the committed GDS is not what the "
            "cited generator produces.")


class PowerPathTests(unittest.TestCase):
    def test_power_path_meets_500ma_row(self):
        """check_layout.py measures the committed GDS and passes the 500 mA EM row."""
        r = run("check_layout.py")
        self.assertEqual(r.returncode, 0,
                         "check_layout.py failed (%d):\n%s%s" % (r.returncode, r.stdout, r.stderr))

    def test_cut_coverage_assertion_bites_in_both_directions(self):
        """The coverage assertion names orphan cuts below AND above on a violating GDS.

        The committed GDS is clean in all six probes; this mutant re-creates the
        two orphan classes #182 fixed -- a Via1 under Metal2 with no Metal1
        below it (the 1260), and a Via1 on Metal1 with no Metal2 above it (the
        720) -- and asserts check_layout.py exits non-zero naming both. A
        below-only proof does not satisfy the AC.
        """
        info = _GEN["info"]
        rows_bot = info["rows_y"]["HS"][0]   # HS row-0 gate-rail bottom = COMP base - 5.1
        w = info["width_um"]
        ly = db.Layout()
        ly.read(GDS)
        top = ly.top_cell()
        via1 = ly.layer(35, 0)
        # below-orphan: in the HS gate-bus band (Metal2, from the tie clearance
        # out to W) beyond the row extent, where no Metal1 exists
        top.shapes(via1).insert(db.DBox(w - 6.0, rows_bot - 2.35, w - 6.0 + 0.26, rows_bot - 2.35 + 0.26))
        # above-orphan: on the row-0 gate-rail Metal1 (full width) inside a strap
        # gap of period x0 = 288 (gap 299.7..300.3), where no Metal2 exists
        top.shapes(via1).insert(db.DBox(299.87, rows_bot + 0.55, 299.87 + 0.26, rows_bot + 0.55 + 0.26))
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "mutant.gds")
            ly.write(p)
            r = run("check_layout.py", "--gds", p)
        self.assertNotEqual(r.returncode, 0,
                            "coverage assertion did not bite on orphan cuts:\n%s" % r.stdout)
        self.assertIn("not covered by Metal1", r.stdout,
                      "below-direction did not bite:\n%s" % r.stdout)
        self.assertIn("not covered by Metal2", r.stdout,
                      "above-direction did not bite:\n%s" % r.stdout)

    def test_gate_buses_share_no_metal2_with_power_nets(self):
        """The GH/GL Metal2 islands share no metal with any power net's (#201).

        Measured on the committed GDS the way the issue measured the defect:
        one merged Metal2 island per labelled gate bus, zero shared area with
        every power net's propagated Metal2, and zero Via2 cuts on the island
        touching Metal3. The pre-fix GDS measured 3.9 um^2 shared and 45
        trunk-reaching cuts per gate bus.
        """
        ly = db.Layout()
        ly.read(GDS)
        top = ly.top_cell()
        um = 1000
        R = {n: db.Region(top.begin_shapes_rec(ly.layer(*l)))
             for n, l in (("METAL2", (36, 0)), ("METAL3", (42, 0)), ("VIA2", (38, 0)))}
        texts = {}
        for lay in ((36, 10), (42, 10)):
            it = top.begin_shapes_rec(ly.layer(*lay))
            while not it.at_end():
                s = it.shape()
                if s.is_text():
                    t = s.text.transformed(it.trans())
                    texts[t.string] = (t.x, t.y)
                it.next()
        m2, m3 = R["METAL2"].merged(), R["METAL3"].merged()

        def at(region, pt):
            return region.interacting(db.Region(db.Box(pt[0] - 1, pt[1] - 1, pt[0] + 1, pt[1] + 1)))
        trunk = {n: at(m3, texts[n]) for n in ("VIN", "SW", "GND")}
        for t in ("GH", "GL"):
            island = at(m2, texts[t])
            for net, tr in trunk.items():
                v2n = db.Region([p for p in R["VIA2"].each()
                                 if not (tr & db.Region(p.bbox())).is_empty()])
                shared = m2.interacting(v2n) & island
                self.assertEqual(shared.area(), 0,
                                 "gate %s shares %.3f um^2 of Metal2 with %s"
                                 % (t, shared.area() / um, net))
            cuts = [p for p in R["VIA2"].each() if not (island & db.Region(p.bbox())).is_empty()]
            on_m3 = [p for p in cuts if not (m3 & db.Region(p.bbox())).is_empty()]
            self.assertEqual(len(on_m3), 0,
                             "gate %s island carries %d Via2 cuts touching Metal3" % (t, len(on_m3)))

    def test_gate_short_checker_bites_on_bus_tie_bridge(self):
        """A Metal2 bridge from a gate bus into a body-tie strip must fail.

        Re-creates the #201 class on the committed GDS: one drawn Metal2 rect
        overlapping both the GL bus and the tie strip merges the two nets, and
        the tie's Via2 cuts make the short visible to the net-level Metal2 the
        checker propagates.
        """
        info = _GEN["info"]
        rows_top = info["rows_y"]["LS"][1]    # LS gate-bus band sits rows_top+1.5 .. +3.0
        ly = db.Layout()
        ly.read(GDS)
        top = ly.top_cell()
        top.shapes(ly.layer(36, 0)).insert(db.DBox(-6.5, rows_top + 1.5, -4.0, rows_top + 3.0))
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "mutant.gds")
            ly.write(p)
            r = run("check_layout.py", "--gds", p)
        self.assertNotEqual(r.returncode, 0,
                            "checker did not bite on a bus-to-tie Metal2 bridge:\n%s" % r.stdout)
        self.assertIn("gate GL shorts to GND", r.stdout,
                      "short not named:\n%s" % r.stdout)


if __name__ == "__main__":
    unittest.main()
